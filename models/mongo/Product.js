const { Schema, model } = require('mongoose');

const ProductSchema = new Schema({
  name: { type: String, required: true },
  slug: { type: String, required: true, unique: true },
  import_source_key: { type: String, default: undefined },
  description: String,
  category: {type:String,trim:true,maxlength:80,default:''},
  department: {type:String,trim:true,maxlength:40,default:''},
  kids_subcategory: {type:String,trim:true,maxlength:40,default:''},
  product_type: {type:String,trim:true,maxlength:60,default:''},
  style: {type:String,trim:true,maxlength:60,default:''},
  fit: {type:String,trim:true,maxlength:60,default:''},
  status: {type:String,enum:['active','draft','coming_soon'],default:'active'},
  featured: {type:Boolean,default:false},
  available_sizes: {type:[String],default:[]},
  size_prices: {type:[new Schema({size:String,price:{type:Number,min:0,max:1000000}},{_id:false})],default:[]},
  pattern_options: {type:new Schema({printable:Boolean,physical:Boolean,trial:Boolean},{_id:false}),default:undefined},
  printable_dimensions: {type:String,maxlength:500,default:''},
  sample_image_url: {type:String,default:''},
  video_url: {type:String,default:''},
  digital_file:{type:String,select:false},
  digital_file_map:{type:[new Schema({format:{type:String,enum:['dxf','hpgl','plt','pdf'],required:true},size:{type:String,required:true},file:{type:String,required:true},original_name:String},{_id:false})],default:[],select:false},
  size_information: {type:String,maxlength:3000,default:''},
  file_formats: {type:String,maxlength:500,default:''},
  delivery_information: {type:String,maxlength:3000,default:''},
  download_information: {type:String,maxlength:3000,default:''},
  seo_title: {type:String,maxlength:200,default:''},
  seo_description: {type:String,maxlength:320,default:''},
  amazon_listing_url: {type:String,default:'',validate:value=>!value || require('../../services/productMetadata').amazonUrl(value)},
  base_price: { type: Number, default: 0, min: 0, max: 1000000 },
  format_pricing: {
    type: new Schema({
      dxf: { type: Number, default: 0, min: 0, max: 1000000 },
      hpgl: { type: Number, default: 0, min: 0, max: 1000000 },
      plt: { type: Number, default: 0, min: 0, max: 1000000 },
      pdf: { type: Number, default: 0, min: 0, max: 1000000 },
      bundle_price: { type: Number, default: 0, min: 0, max: 1000000 },
      active_bundle: { type: Boolean, default: false }
    }, { _id: false }),
    default: () => ({ dxf: 0, hpgl: 0, plt: 0, pdf: 0, bundle_price: 0, active_bundle: false })
  },
  tech_pack_price: { type: Number, default: 0, min: 0, max: 1000000 },
  marker_service_price: { type: Number, default: 0, min: 0, max: 1000000 },
  size_chart_image: { type: String, default: '' },
  size_chart_url: { type: String, default: '' },
  size_chart_pdf: { type: String, default: '' },
  size_chart_pdf_name: { type: String, default: '' },
  size_chart_visible: { type: Boolean, default: true },
  additional_size_price: { type: Number, default: 0, min: 0, max: 1000000 },
  physical_price: { type: Number, default: 0, min: 0, max: 1000000 },
  trial_price: { type: Number, default: 0, min: 0, max: 1000000 },
  images: { type: [String], default: [] },
  finished_garment_images: { type: [String], default: [] },
  active: { type: Boolean, default: true },
}, { timestamps: true });

module.exports = model('Product', ProductSchema);
